/** Converte um id possivelmente antigo para o id atual. */
export function resolveClubId(id: string | null | undefined): string | null {
  if (!id) return null;
  if (CLUB_BY_ID[id]) return id;
  return LEGACY_CLUB_IDS[id] ?? id;
}

export function getClub(id: string | null | undefined): Club | undefined {
  if (!id) return undefined;
  return CLUB_BY_ID[id] ?? CLUB_BY_ID[LEGACY_CLUB_IDS[id] ?? ''];
}

export function getLeague(id: string): League {
  return LEAGUE_BY_ID[id] ?? LEAGUES[0];
}

export function clubsInLeague(leagueId: string): Club[] {
  return CLUBS.filter((c) => c.leagueId === leagueId);
}

/** Clubes de um país (independe da liga em que jogam). */
export function clubsOfCountry(country: string): Club[] {
  return CLUBS.filter((c) => c.country === country);
}

